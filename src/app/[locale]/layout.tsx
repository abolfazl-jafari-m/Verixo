import type { Metadata } from "next";
import { Geist, Geist_Mono, Inter, Vazirmatn } from "next/font/google";
import "../globals.css";
import { cn } from "@/lib/utils";
import { notFound } from "next/navigation";
import { hasLocale } from "next-intl";
import { routing } from "@/lib/i18n/routing";
import { OrdersProvider } from "@/features/orders/components/orders-provider/orders-provider";
import AppProvider from "@/providers/app-provider";

const inter = Inter({ subsets: ["latin"], variable: "--font-inter" });

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});
const vazirmatn = Vazirmatn({
  variable: "--font-varzir",
  subsets: ["arabic"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Verixo",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
  params,
}: Readonly<{
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}>) {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) {
    notFound();
  }
  return (
    <html
      lang={locale}
      suppressHydrationWarning
      className={cn(
        "h-full",
        "antialiased",
        vazirmatn.variable,
        inter.variable,
        geistMono.variable,
        geistSans.variable,
        "font-sans",
      )}
    >
      <body dir={locale === "fa" ? "rtl" : "ltr"} className="flex min-h-full flex-col">
        <AppProvider locale={locale}>
          <OrdersProvider>{children}</OrdersProvider>
        </AppProvider>
      </body>
    </html>
  );
}
